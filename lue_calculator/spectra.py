    """
    获取叶绿素吸收光谱（作为植物PAR响应函数）
    
    参数:
        wavelengths: 可选，指定的波长数组，如果提供则插值到这些波长点
        
    返回:
        (wavelengths, response): 波长(nm)和吸收响应(归一化到1)
    """
    if wavelengths is None:
        return CHLOROPHYLL_WAVELENGTHS.copy(), CHLOROPHYLL_ABSORPTION.copy()
    
    # 插值到指定波长
    interp_func = interp1d(CHLOROPHYLL_WAVELENGTHS, CHLOROPHYLL_ABSORPTION,
                           kind='linear', bounds_error=False, fill_value=0)
