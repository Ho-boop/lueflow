def interpolate_spectrum(wavelengths: np.ndarray, values: np.ndarray, 
                         target_wavelengths: np.ndarray) -> np.ndarray:
    """
    将光谱数据插值到目标波长点
    
    参数:
        wavelengths: 原始波长数组
        values: 原始数值数组
        target_wavelengths: 目标波长数组
        
    返回:
        插值后的数值数组
    """
    interp_func = interp1d(wavelengths, values, kind='linear', 
                           bounds_error=False, fill_value=0)
    return interp_func(target_wavelengths)
