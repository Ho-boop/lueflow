def get_am15g_spectrum(wavelengths: np.ndarray = None) -> Tuple[np.ndarray, np.ndarray]:
    """
    获取AM1.5G太阳光谱数据
    
    参数:
        wavelengths: 可选，指定的波长数组，如果提供则插值到这些波长点
        
    返回:
        (wavelengths, irradiance): 波长(nm)和辐照度(W/m²/nm)
    """
    if wavelengths is None:
        return AM15G_WAVELENGTHS.copy(), AM15G_IRRADIANCE.copy()
    
    # 插值到指定波长
    interp_func = interp1d(AM15G_WAVELENGTHS, AM15G_IRRADIANCE, 
                           kind='linear', bounds_error=False, fill_value=0)
    return wavelengths, interp_func(wavelengths)


def get_photopic_response(wavelengths: np.ndarray = None) -> Tuple[np.ndarray, np.ndarray]:
    """
    获取CIE 1931人眼明视觉响应函数V(λ)
    
    参数:
        wavelengths: 可选，指定的波长数组，如果提供则插值到这些波长点
        
    返回:
        (wavelengths, response): 波长(nm)和响应值(归一化到1)
    """
    if wavelengths is None:
        return PHOTOPIC_WAVELENGTHS.copy(), PHOTOPIC_RESPONSE.copy()
    
    # 插值到指定波长
    interp_func = interp1d(PHOTOPIC_WAVELENGTHS, PHOTOPIC_RESPONSE,
                           kind='linear', bounds_error=False, fill_value=0)
    return wavelengths, interp_func(wavelengths)


